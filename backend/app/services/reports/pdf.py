from io import BytesIO
from xml.sax.saxutils import escape
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

def _fmt(dt):
    return dt.strftime("%d %b %Y, %H:%M:%S UTC") if dt else "-"

def build_case_pdf(case_id, case, items, timeline) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=16 * mm, bottomMargin=16 * mm,
                            title=f"Digital Shield case {case_id}")
    ss = getSampleStyleSheet()
    h1, h2, body = ss["Title"], ss["Heading2"], ss["BodyText"]
    small = ParagraphStyle("small", parent=body, fontSize=8, leading=10)

    def P(text, style=small):
        return Paragraph(escape(str(text if text is not None else "-")), style)

    def table(rows, widths, header=False):
        t = Table([[P(c) for c in r] for r in rows], colWidths=widths, repeatRows=1 if header else 0)
        style = [("GRID", (0, 0), (-1, -1), 0.4, colors.grey), ("VALIGN", (0, 0), (-1, -1), "TOP")]
        if header:
            style.append(("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E5E7EB")))
        t.setStyle(TableStyle(style))
        return t

    def footer(canvas, _doc):
        canvas.setFont("Helvetica", 7)
        canvas.drawString(18 * mm, 8 * mm, f"Digital Shield | Case {case_id} | Page {canvas.getPageNumber()}")

    s = [P("Digital Shield: Cyber Incident Report", h1), Spacer(1, 4)]

    s += [P("1. Case details", h2), table([
        ["Case ID", case_id], ["Title", case.get("title")],
        ["Incident type", case.get("incident_type")], ["Status", case.get("status")],
        ["Created", _fmt(case.get("created_at"))],
        ["Highest risk", f"{case['risk']['band']} ({case['risk']['score']}/100)"],
        ["Evidence items", len(items)],
    ], [40 * mm, 134 * mm])]

    s += [P("2. Incident summary", h2),
          P(case.get("description") or "Suspected digital-arrest scam reported through the Digital Shield app.", body)]

    inds = ", ".join(i.replace("_", " ") for i in case.get("indicators", [])) or "none"
    s += [P("3. Scam behaviour indicators observed", h2), P(inds, body)]

    rows = [["#", "Type", "Time", "Risk", "Content", "SHA-256", "Integrity"]]
    for n, it in enumerate(items, 1):
        rows.append([n, it["type"], _fmt(it["time"]), f"{it['risk_band']} {it['risk_score']}",
                     it["label"][:300], it["sha256"] or "-", it["integrity"]])
    s += [P("4. Evidence", h2),
          table(rows, [8 * mm, 18 * mm, 30 * mm, 20 * mm, 50 * mm, 34 * mm, 14 * mm], header=True)]

    iocs = [v.replace(":", ": ", 1) for v in case.get("ioc_values", [])]
    s += [P("5. Indicators of compromise", h2), P("; ".join(iocs) or "none", body)]

    trows = [["Time", "Evidence", "Action", "Actor"]]
    for e in timeline[:60]:
        trows.append([_fmt(e.get("timestamp")), f"{e.get('evidence_type')} {str(e.get('evidence_id'))[-8:]}",
                      e.get("action"), e.get("actor")])
    s += [P("6. Chain of custody", h2), table(trows, [45 * mm, 45 * mm, 50 * mm, 34 * mm], header=True)]

    s += [P("7. Recommended next steps", h2)]
    for line in ["Call the national cyber-crime helpline 1930 as soon as possible.",
                 "File a complaint at cybercrime.gov.in and attach this report.",
                 "If money was transferred, ask your bank to freeze the transaction immediately.",
                 "Do not delete the original messages, call logs or screenshots on the phone."]:
        s.append(P("- " + line, body))

    s += [Spacer(1, 8), P(
        "Generated by Digital Shield, an AI-assisted early-warning tool. Risk scores show scam indicators, "
        "not a legal finding. SHA-256 hashes show the evidence has not changed since capture; courts may "
        "additionally require a certificate for electronic records.", small)]

    doc.build(s, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
